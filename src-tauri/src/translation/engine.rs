//! Native translation engine boundary.
//!
//! This module intentionally does not depend on CTranslate2 directly. Engine
//! adapters implement these contracts so command DTOs and storage semantics
//! stay stable while runtimes change.

use super::types::{TranslationGlossaryEntry, TranslationRepairMode};

/// One bounded batch for an engine, with the job settings that produced it.
///
/// The CTranslate2/OPUS-MT adapter reads only `segments`: pair models encode
/// the language direction, and Marian cannot consume glossary, quality, or
/// repair instructions. Prompt-driven engines such as HY-MT2 also read the
/// language and job-setting fields.
#[derive(Debug, Clone)]
#[allow(dead_code)]
pub(crate) struct TranslationBatchInput {
    pub(crate) model_id: String,
    pub(crate) source_language: String,
    pub(crate) target_language: String,
    pub(crate) quality_mode: String,
    pub(crate) repair_mode: TranslationRepairMode,
    pub(crate) glossary: Vec<TranslationGlossaryEntry>,
    pub(crate) segments: Vec<TranslationSegmentInput>,
}

#[derive(Debug, Clone)]
pub(crate) struct TranslationSegmentInput {
    pub(crate) id: String,
    pub(crate) text: String,
    /// Unread by the OPUS-MT adapter; see `TranslationSegmentContext`.
    #[allow(dead_code)]
    pub(crate) context: TranslationSegmentContext,
}

/// Quality hints attached to one segment.
///
/// Only glossary hints exist today. OPUS-MT ignores free-form context; HY-MT2
/// can consume glossary instructions once the UI exposes them. A future
/// document memory packet (title, headings, neighboring text) belongs here.
#[derive(Debug, Clone, Default)]
#[allow(dead_code)]
pub(crate) struct TranslationSegmentContext {
    pub(crate) glossary: Vec<TranslationGlossaryEntry>,
}

#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct TranslationSegmentOutput {
    pub(crate) id: String,
    /// Exact normalized input, retained by the adapter rather than generated by MT.
    pub(crate) source_text: String,
    pub(crate) text: String,
}

pub(crate) trait TranslationEngine {
    /// Translate a bounded batch of document segments.
    ///
    /// Adapters retain exact segment ids and source text so the caller can
    /// validate replies before caching completed work. Context fields are hints for
    /// quality, not text that should be emitted into the translated output.
    fn translate_batch(
        &mut self,
        input: TranslationBatchInput,
    ) -> Result<Vec<TranslationSegmentOutput>, String>;
}

/// Validate the whole reply before any output is associated with a block or cached.
pub(super) fn validate_outputs(
    expected: &[(&str, &str)],
    outputs: &[TranslationSegmentOutput],
) -> Result<(), String> {
    let mut ids = std::collections::BTreeSet::new();
    if expected
        .iter()
        .any(|(id, source)| id.is_empty() || source.trim().is_empty() || !ids.insert(*id))
    {
        return Err("Translation batch contains invalid segment identities or source text".into());
    }
    if expected.len() != outputs.len()
        || expected
            .iter()
            .zip(outputs)
            .any(|((id, source), output)| *id != output.id || *source != output.source_text)
    {
        return Err(
            "Translation engine returned mismatched segment identities or source text".into(),
        );
    }
    if outputs.iter().any(|output| output.text.trim().is_empty()) {
        return Err("Translation engine returned empty output".into());
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn rejects_missing_extra_duplicate_and_reordered_replies() {
        let output = |id: &str| TranslationSegmentOutput {
            id: id.into(),
            source_text: "source".into(),
            text: "translated".into(),
        };
        for replies in [
            vec![],
            vec![output("a")],
            vec![output("a"), output("b"), output("c")],
            vec![output("a"), output("a")],
            vec![output("b"), output("a")],
        ] {
            assert!(validate_outputs(&[("a", "source"), ("b", "source")], &replies).is_err());
        }
        assert!(validate_outputs(
            &[("a", "source"), ("b", "source")],
            &[output("a"), output("b")]
        )
        .is_ok());
        assert!(validate_outputs(
            &[("a", "source"), ("a", "source")],
            &[output("a"), output("a")]
        )
        .is_err());
    }

    #[test]
    fn binds_exact_unicode_source_and_validates_all_text_before_consumption() {
        let expected = [("b0:s0", "Résumé 港🙂 عَرَبِيّ"), ("b1:s0", "Encore")];
        let mut outputs = expected
            .iter()
            .map(|(id, text)| TranslationSegmentOutput {
                id: (*id).into(),
                source_text: (*text).into(),
                text: "Translated".into(),
            })
            .collect::<Vec<_>>();
        assert!(validate_outputs(&expected, &outputs).is_ok());
        outputs[1].text = " \n\t".into();
        assert!(validate_outputs(&expected, &outputs)
            .unwrap_err()
            .contains("empty output"));
        outputs[1].text = "Translated".into();
        for stale in [
            "Resume 港🙂 عَرَبِيّ",
            "Re\u{301}sume\u{301} 港🙂 عَرَبِيّ",
            "Résumé 港🙂 عَرَبِيّ ",
        ] {
            outputs[0].source_text = stale.into();
            assert!(validate_outputs(&expected, &outputs)
                .unwrap_err()
                .contains("source text"));
        }
        assert!(validate_outputs(&[("", "source")], &outputs[..1]).is_err());
        assert!(validate_outputs(&[("b0:s0", " ")], &outputs[..1]).is_err());
        assert!(validate_outputs(&[], &[]).is_ok());
    }
}
